/**
 * Emit `src/abis.ts` from the Foundry build artefacts.
 *
 * The ABIs are committed as `as const` TypeScript rather than read from JSON at
 * runtime: viem derives its argument and return types from the literal, so a
 * contract change becomes a compile error in the API and the worker instead of
 * a runtime decode failure in production.
 *
 * Run after `forge build`:  node scripts/generate-abis.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '../../../contracts/out');
const names = ['Governance', 'IssuerRegistry', 'StatusRegistry', 'AnchorRegistry', 'AuditAnchor'];

const parts = [
  '/**',
  ' * Contract ABIs — GENERATED by scripts/generate-abis.mjs from `forge build`.',
  ' * Do not edit by hand; run the generator after changing a contract.',
  ' */',
  '',
];

for (const name of names) {
  const artefact = join(outDir, `${name}.sol`, `${name}.json`);
  if (!existsSync(artefact)) {
    console.error(`missing artefact for ${name} — run \`forge build\` first (${artefact})`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(artefact, 'utf8'));
  const constName = `${name.charAt(0).toLowerCase()}${name.slice(1)}Abi`;
  parts.push(`export const ${constName} = ${JSON.stringify(abi, null, 2)} as const;`, '');
}

writeFileSync(resolve(here, '../src/abis.ts'), parts.join('\n'));
console.log(`wrote src/abis.ts (${names.length} contracts)`);
